"""Corpus dashboard: browse multiple per-app HTML reports from one index page.

Stdlib-only. Discovers Django/Spring application roots under a corpus
directory, runs the existing PFG → rules → HTML pipeline for each, and
emits a navigable ``index.html`` linking to each per-app report.
"""

from __future__ import annotations

import html
import traceback
from dataclasses import dataclass
from pathlib import Path

from pfg.detectors.rule_baseline import detect_all
from pfg.pfg.graph import PFG
from pfg.report.html import write_report


@dataclass(frozen=True)
class DashboardEntry:
    app: str
    framework: str
    report_href: str
    n_endpoints: int
    n_findings: int
    error: str | None = None


