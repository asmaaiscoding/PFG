def _row_html(e: DashboardEntry) -> str:
    if e.error is not None:
        pill = '<span class="pill pill-warn">ERROR</span>'
        link = html.escape(e.app)
        why = f'<td class="mono" colspan="2">{html.escape(e.error)}</td>'
        return (
            f'<tr class="row"><td>{pill}</td>'
            f'<td>{link}</td>'
            f'<td class="mono">{html.escape(e.framework)}</td>'
            f'{why}</tr>'
        )
    if e.n_findings == 0:
        pill = '<span class="pill pill-ok">CLEAN</span>'
    else:
        pill = f'<span class="pill pill-bad">{e.n_findings} finding{"s" if e.n_findings != 1 else ""}</span>'
    href = html.escape(e.report_href)
    name = html.escape(e.app)
    return (
        f'<tr class="row" onclick="window.location=\'{href}\'">'
        f'<td>{pill}</td>'
        f'<td><a href="{href}">{name}</a></td>'
        f'<td class="mono">{html.escape(e.framework)}</td>'
        f'<td class="mono">{e.n_endpoints}</td>'
        f'<td class="mono">{e.n_findings}</td>'
        f'</tr>'
    )


def render_dashboard(entries: list[DashboardEntry], *, title: str = "PFG Dashboard") -> str:
    if not entries:
        table = '<div class="empty">No applications found.</div>'
    else:
        rows = "".join(_row_html(e) for e in entries)
        table = (
            "<table>"
            "<thead><tr>"
            "<th>Status</th><th>Application</th><th>Framework</th>"
            "<th>Endpoints</th><th>Findings</th>"
            "</tr></thead>"
            f"<tbody>{rows}</tbody>"
            "</table>"
        )
    total_endpoints = sum(e.n_endpoints for e in entries if e.error is None)
    total_findings = sum(e.n_findings for e in entries if e.error is None)
    n_apps_flagged = sum(1 for e in entries if e.error is None and e.n_findings > 0)
    subtitle = f"{len(entries)} applications · {total_findings} findings across {total_endpoints} endpoints"
    return _INDEX_TEMPLATE.format(
        title=html.escape(title),
        subtitle=html.escape(subtitle),
        n_apps=len(entries),
        total_endpoints=total_endpoints,
        total_findings=total_findings,
        n_apps_flagged=n_apps_flagged,
        table=table,
    )


def _looks_like_django(p: Path) -> bool:
    if not p.is_dir():
        return False
    for marker in ("manage.py", "urls.py", "settings.py", "views.py"):
        if (p / marker).exists():
            return True
    return False


def _looks_like_spring(p: Path) -> bool:
    if not p.is_dir():
        return False
    if (p / "pom.xml").exists():
        return True
    if any(p.glob("build.gradle*")):
        return True
    return (p / "src" / "main" / "java").is_dir()


def discover_apps(corpus_root: Path, framework: str) -> list[Path]:
    """Find application roots under `corpus_root`.

    If `corpus_root` itself looks like an app, return `[corpus_root]`.
    Otherwise return any immediate children that look like apps.
    """
    corpus_root = Path(corpus_root)
    check = _looks_like_django if framework == "django" else _looks_like_spring
    if check(corpus_root):
        return [corpus_root]
    apps: list[Path] = []
    if corpus_root.is_dir():
        for child in sorted(corpus_root.iterdir()):
            if child.is_dir() and not child.name.startswith(".") and check(child):
                apps.append(child)
    return apps


def _build_one(app_root: Path, framework: str) -> PFG:
    if framework == "django":
        from pfg.extractors.django.build import build_pfg as _build
    else:
        from pfg.extractors.spring.build import build_pfg as _build
    return _build(app_root, application=app_root.name)


def build_dashboard(
    corpus_root: Path,
    out_dir: Path,
    *,
    framework: str = "django",
    title: str | None = None,
) -> Path:
    """Analyze every app under `corpus_root` and emit `out_dir/index.html`."""
    corpus_root = Path(corpus_root)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    apps = discover_apps(corpus_root, framework)
    entries: list[DashboardEntry] = []
    for app in apps:
        report_path = out_dir / f"{app.name}.html"
        try:
            pfg = _build_one(app, framework)
            findings = detect_all(pfg)
            n_endpoints = sum(
                1 for n in pfg.nodes if getattr(n.type, "value", n.type) == "endpoint"
            )
            write_report(pfg, report_path, findings=findings)
            entries.append(
                DashboardEntry(
                    app=app.name,
                    framework=framework,
                    report_href=report_path.name,
                    n_endpoints=n_endpoints,
                    n_findings=len(findings),
                )
            )
        except Exception as exc:
            entries.append(
                DashboardEntry(
                    app=app.name,
                    framework=framework,
                    report_href="",
                    n_endpoints=0,
                    n_findings=0,
                    error=f"{type(exc).__name__}: {exc}".splitlines()[0]
                    or traceback.format_exc(limit=1).strip(),
                )
            )

    index = out_dir / "index.html"
    index.write_text(
        render_dashboard(entries, title=title or f"PFG Dashboard — {corpus_root.name}"),
        encoding="utf-8",
    )
    return index
